#define ZEDA_DEF_TREE_CLASS_PROPERTY(node_t,data_t) \
  node_t *parent; \
  node_t *child[2]; \
  uint size; \
  data_t data;

#ifdef __cplusplus
#define ZEDA_DEF_TREE_CLASS_CPP_METHOD(node_t,data_t) \
  node_t() : parent{NULL}, child{ NULL, NULL }, size{0} {} \
  ~node_t(){} \
  node_t *init(){ return node_t##Init( this ); } \
  void destroy(){ node_t##Destroy( this ); } \
  bool isEmpty(){ return zTreeIsEmpty( this ); } \
  bool isLeaf(){ return zTreeIsLeaf( this ); }
#endif /* __cplusplus */

#define ZEDA_DEF_TREE_CLASS_INIT_PROTOTYPE(node_t)         node_t *node_t##Init(node_t *node)
#define ZEDA_DEF_TREE_CLASS_DESTROY_PROTOTYPE(node_t)      void node_t##Destroy(node_t *tree)
#define ZEDA_DEF_TREE_CLASS_ALLOC_PROTOTYPE(node_t,data_t) node_t *node_t##NodeAlloc(const data_t *val)

#define ZEDA_DEF_TREE_CLASS_METHOD_PROTOTYPE(method_export,node_t,data_t) \
method_export ZEDA_DEF_TREE_CLASS_INIT_PROTOTYPE(node_t); \
method_export ZEDA_DEF_TREE_CLASS_DESTROY_PROTOTYPE(node_t); \
method_export ZEDA_DEF_TREE_CLASS_ALLOC_PROTOTYPE(node_t,data_t);

/*! \def ZEDA_DEF_TREE_CLASS(node_t,data_t)
 * \brief generate binary tree class.
 *
 * A macro ZEDA_DEF_TREE_CLASS() generates a new binary tree class and
 * prototypes of some associated methods.
 *
 * The tree class \a tree_t defines a node that contains data
 * with the type \a data_t and two pointers to children.
 *
 * The methods to be generated are (node_t)Init(), (node_t)Destroy(),
 * and (node_t)NodeAlloc(), where (node_t)s are replaced by the
 * actual type name. The body implementation of those functions
 * are generated by calling ZEDA_DEF_TREE_CLASS_METHOD(node_t, data_t);
 *
 * The methods (node_t)UpHeap, (node_t)AddHeap(), (node_t)DownHeap,
 * (node_t)GetHeap(), and (node_t)Heapify() are additionally
 * defined by calling ZEDA_DEF_HEAP_CLASS() and ZEDA_DEF_HEAP_CLASS_METHOD() instead
 * of ZEDA_DEF_TREE_CLASS() and ZEDA_DEF_TREE_CLASS_METHOD().
 */
#ifdef __cplusplus
#define ZEDA_DEF_TREE_CLASS(method_export,node_t,data_t) \
ZDECL_STRUCT( node_t ); \
ZEDA_DEF_TREE_CLASS_METHOD_PROTOTYPE( method_export, node_t, data_t ) \
ZDEF_STRUCT( , node_t ){ \
  ZEDA_DEF_TREE_CLASS_PROPERTY( node_t, data_t ) \
 public: \
  ZEDA_DEF_TREE_CLASS_CPP_METHOD( node_t, data_t ) \
};
#else
#define ZEDA_DEF_TREE_CLASS(method_export,node_t,data_t) \
ZDEF_STRUCT( , node_t ){ \
  ZEDA_DEF_TREE_CLASS_PROPERTY( node_t, data_t ) \
}; \
ZEDA_DEF_TREE_CLASS_METHOD_PROTOTYPE( method_export, node_t, data_t )
#endif /* __cplusplus */

#define ZEDA_DEF_TREE_CLASS_METHOD(node_t,data_t,init,destroy) \
static data_t *(* _##node_t##DataInit)(data_t *) = init; \
static void (* _##node_t##DataDestroy)(data_t *) = destroy; \
\
ZEDA_DEF_TREE_CLASS_INIT_PROTOTYPE(node_t){ \
  if( _##node_t##DataInit ) _##node_t##DataInit( &(node)->data ); \
  node->parent = node->child[0] = node->child[1] = NULL; \
  node->size = 0; \
  return node; \
} \
\
static void __##node_t##NodeDestroy(node_t *node){ \
  if( node->child[0] ) \
    __##node_t##NodeDestroy( node->child[0] ); \
  if( node->child[1] ) \
    __##node_t##NodeDestroy( node->child[1] ); \
  if( _##node_t##DataDestroy ) _##node_t##DataDestroy( &(node)->data ); \
  free( node ); \
} \
\
ZEDA_DEF_TREE_CLASS_DESTROY_PROTOTYPE(node_t){ \
  if( tree->child[0] ) \
    __##node_t##NodeDestroy( tree->child[0] ); \
  node_t##Init( tree ); \
} \
\
ZEDA_DEF_TREE_CLASS_ALLOC_PROTOTYPE(node_t,data_t){ \
  node_t *node; \
  if( !( node = zAlloc( node_t, 1 ) ) ){ \
    ZALLOCERROR(); \
    return NULL; \
  } \
  node_t##Init( node ); \
  memcpy( (void *)&node->data, (const void *)val, sizeof(data_t) ); \
  return node; \
}

